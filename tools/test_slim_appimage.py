"""DESK-037 / DESK-038 (ADR-0022): the AppImage relies on the system WebKitGTK (08 §4.1) and says so when it is missing.

DESK-037: the slimmed AppDir holds none of WebKitGTK's library closure, nor the GTK hook and modules that pointed the
app at bundled copies; the app's own libraries (pg pack, Python, tray) stay.
DESK-038: the AppRun preflight hook stops the launch with DESK_WEBVIEW_MISSING (reason and fix, both languages from
packages/i18n) when libwebkit2gtk-4.1 is absent, and lets it continue when it is present."""

import json
import subprocess
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent))
import slim_appimage as S

ROOT = Path(__file__).resolve().parents[1]
CLOSURE = {"libwebkit2gtk-4.1.so.0", "libjavascriptcoregtk-4.1.so.0", "libgtk-3.so.0", "libicuuc.so.70", "libxml2.so.2"}


def _appdir(tmp: Path) -> Path:
    ad = tmp / "OpenPhotoAgent.AppDir"
    lib = ad / "usr/lib"
    for name in [
        "libwebkit2gtk-4.1.so.0",
        "libjavascriptcoregtk-4.1.so.0.2.7",
        "libgtk-3.so.0",
        "libicuuc.so.70",
        "libxml2.so.2",
        "libayatana-appindicator3.so.1",  # tray: loaded by the shell, not part of WebKitGTK's closure
        "libpq.so.5",
    ]:
        (lib / name).parent.mkdir(parents=True, exist_ok=True)
        (lib / name).write_bytes(b"\x7fELF")
    (lib / "x86_64-linux-gnu/webkit2gtk-4.1/injected-bundle").mkdir(parents=True)
    (lib / "x86_64-linux-gnu/gdk-pixbuf-2.0/2.10.0/loaders").mkdir(parents=True)
    (lib / "x86_64-linux-gnu/gtk-3.0/3.0.0/immodules").mkdir(parents=True)
    (lib / "x86_64-linux-gnu/gio/modules").mkdir(parents=True)
    (ad / "usr/share/glib-2.0/schemas").mkdir(parents=True)
    (ad / "usr/lib/OpenPhotoAgent/python/lib/libpython3.12.so.1.0").parent.mkdir(parents=True)
    (ad / "usr/lib/OpenPhotoAgent/python/lib/libpython3.12.so.1.0").write_bytes(b"\x7fELF")
    (ad / "usr/lib/OpenPhotoAgent/pg/lib/libxml2.so.2").parent.mkdir(parents=True)
    (ad / "usr/lib/OpenPhotoAgent/pg/lib/libxml2.so.2").write_bytes(b"\x7fELF")  # pack-private copy
    (ad / "apprun-hooks").mkdir()
    (ad / "apprun-hooks/linuxdeploy-plugin-gtk.sh").write_text("export GTK_DATA_PREFIX=$APPDIR\n", encoding="utf-8")
    (ad / "apprun-hooks/linuxdeploy-plugin-other.sh").write_text("export OPA_OTHER_HOOK=ran\n", encoding="utf-8")
    # what linuxdeploy writes when plugins add hooks: each hook sourced by name, then the real entry point
    (ad / "AppRun").write_text(
        "#! /usr/bin/env bash\n\n# autogenerated by linuxdeploy\n\n"
        'this_dir="$(readlink -f "$(dirname "$0")")"\n\n'
        'source "$this_dir"/apprun-hooks/"linuxdeploy-plugin-gtk.sh"\n'
        'source "$this_dir"/apprun-hooks/"linuxdeploy-plugin-other.sh"\n\n'
        'exec "$this_dir"/AppRun.wrapped "$@"\n',
        encoding="utf-8",
    )
    (ad / "AppRun").chmod(0o755)
    (ad / "AppRun.wrapped").write_text('#!/bin/sh\necho "continued $OPA_OTHER_HOOK $*"\n', encoding="utf-8")
    (ad / "AppRun.wrapped").chmod(0o755)
    return ad


@pytest.mark.unit
@pytest.mark.tc("DESK-037")
def test_desk_037_appdir_carries_no_webkitgtk_closure(tmp_path):
    ad = _appdir(tmp_path)
    removed = S.slim(ad, CLOSURE)
    left = {p.name for p in (ad / "usr/lib").iterdir() if p.is_file()}
    assert left == {"libayatana-appindicator3.so.1", "libpq.so.5"}
    for gone in ["webkit2gtk-4.1", "gdk-pixbuf-2.0", "gtk-3.0", "gio"]:
        assert not (ad / "usr/lib/x86_64-linux-gnu" / gone).exists(), gone
    assert not (ad / "usr/share/glib-2.0/schemas").exists()
    assert not (ad / "apprun-hooks/linuxdeploy-plugin-gtk.sh").exists()
    apprun = (ad / "AppRun").read_text(encoding="utf-8")
    assert "linuxdeploy-plugin-gtk.sh" not in apprun and "linuxdeploy-plugin-other.sh" in apprun
    assert apprun.index(S.HOOK.split("/")[1]) < apprun.index("linuxdeploy-plugin-other.sh")
    # the resources tree is the app's own: never touched, even where a soname coincides
    assert (ad / "usr/lib/OpenPhotoAgent/python/lib/libpython3.12.so.1.0").exists()
    assert (ad / "usr/lib/OpenPhotoAgent/pg/lib/libxml2.so.2").exists()
    assert (ad / S.HOOK).is_file()
    assert "usr/lib/libgtk-3.so.0" in removed
    assert S.verify(ad, CLOSURE) == []
    (ad / "usr/lib/libwebkit2gtk-4.1.so.0").write_bytes(b"\x7fELF")
    assert S.verify(ad, CLOSURE) == ["usr/lib/libwebkit2gtk-4.1.so.0"]


def _run_hook(ad: Path, libdirs: str) -> subprocess.CompletedProcess[str]:
    # the rewritten AppRun, as the AppImage runtime starts it; the app only runs when the hook lets it
    return subprocess.run(
        [str(ad / "AppRun"), "--flag"],
        env={"PATH": "/usr/bin:/bin", "OPAGENT_WEBVIEW_LIBDIRS": libdirs, "DISPLAY": ""},
        capture_output=True,
        text=True,
        check=False,
    )


@pytest.mark.unit
@pytest.mark.os_linux  # executes the AppImage's shell hook; AppImage only exists on Linux
@pytest.mark.tc("DESK-038")
def test_desk_038_apprun_preflight_explains_a_missing_webview(tmp_path):
    ad = _appdir(tmp_path)
    S.slim(ad, CLOSURE)
    empty = tmp_path / "nolibs"
    empty.mkdir()
    r = _run_hook(ad, str(empty))
    assert r.returncode == S.EXIT_WEBVIEW_MISSING and "continued" not in r.stdout
    zh = json.loads((ROOT / "packages/i18n/errors.zh-TW.json").read_text(encoding="utf-8"))["DESK_WEBVIEW_MISSING"]
    en = json.loads((ROOT / "packages/i18n/errors.en.json").read_text(encoding="utf-8"))["DESK_WEBVIEW_MISSING"]
    for text in ["DESK_WEBVIEW_MISSING", zh["message"], zh["cta"], en["message"], en["cta"]]:
        assert text.replace("{lib}", S.WEBVIEW_SONAME) in r.stderr, text
    for cmd in ["apt install libwebkit2gtk-4.1-0", "dnf install webkit2gtk4.1", "pacman -S webkit2gtk-4.1"]:
        assert cmd in r.stderr, cmd  # a fix the user can act on, per distribution (invariant 8)
    have = tmp_path / "libs"
    have.mkdir()
    (have / S.WEBVIEW_SONAME).write_bytes(b"\x7fELF")
    r = _run_hook(ad, f"{empty} {have}")
    assert r.returncode == 0 and r.stdout.strip() == "continued ran --flag" and r.stderr == ""
