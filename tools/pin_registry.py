"""Resolve built-in catalog refs to commits and write registry/pins.lock (ADR-0002).

Run by .github/workflows/registry-pin.yml (needs network access to Hugging Face). ``--check`` only verifies that
every existing pin still resolves (nightly drift check, catches future DL_NOT_FOUND).

    uv run --with huggingface_hub python tools/pin_registry.py [--check]
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1] / "packages/registry/src/opagent_registry/builtin"
HEADER = "# Generated by .github/workflows/registry-pin.yml (ADR-0002). Do not edit by hand.\n"


def main() -> int:
    from huggingface_hub import HfApi  # type: ignore[import-not-found]

    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    api = HfApi()
    lock_text = "\n".join(
        ln for ln in (ROOT / "pins.lock").read_text(encoding="utf-8").splitlines() if not ln.startswith("#")
    )
    old = {(p["model"], p["variant"]): p for p in json.loads(lock_text or "{}").get("pins", [])}
    pins, problems = [], []
    for path in sorted((ROOT / "models").glob("*.yaml")):
        spec = yaml.safe_load(path.read_text(encoding="utf-8"))
        for v in spec["variants"]:
            repos = {f["repo"] for f in v.get("files", [])}
            if not repos:
                continue
            prev = old.get((spec["id"], v["id"]))
            ref = prev["revision"] if (args.check and prev) else v.get("revision", "main")
            files, revision = [], None
            for repo in sorted(repos):
                try:
                    info = api.model_info(repo, revision=ref, files_metadata=True)
                except Exception as e:
                    problems.append(f"{spec['id']}@{v['id']}: {repo}@{ref}: {e}")
                    break
                revision = revision or info.sha
                by_name = {s.rfilename: s for s in info.siblings or []}
                for f in (f for f in v["files"] if f["repo"] == repo):
                    s = by_name.get(f["path"])
                    if s is None or (s.lfs is None and s.size is None):
                        problems.append(f"{spec['id']}@{v['id']}: {repo}/{f['path']} not found at {info.sha}")
                        continue
                    sha = s.lfs.sha256 if s.lfs else None
                    if sha is None:
                        problems.append(f"{spec['id']}@{v['id']}: {f['path']} has no LFS sha256")
                        continue
                    files.append({"path": f["path"], "size": s.size, "sha256": sha, "lfs_oid": sha})
            if revision and len(files) == len(v["files"]):
                pins.append({"model": spec["id"], "variant": v["id"], "revision": revision, "files": files})
    for p in problems:
        print("::warning::" + p)
    if args.check:
        return 1 if problems else 0
    (ROOT / "pins.lock").write_text(
        HEADER + json.dumps({"schema_version": 1, "pins": pins}, indent=2) + "\n", encoding="utf-8"
    )
    print(f"pinned {len(pins)} variants; {len(problems)} problems")
    return 0


if __name__ == "__main__":
    sys.exit(main())
