"""One ProblemCard story per error code (VIS-003): apps/web/src/components/ProblemCard.generated.stories.tsx.

Generated from packages/i18n/errors.zh-TW.json (itself generated from 06 §4.7) and the doctor catalog's fixes.
``--check`` fails when the file is out of date; a contract test also compares the story count to the catalog.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
ERRORS = ROOT / "packages" / "i18n" / "errors.zh-TW.json"
CATALOG = ROOT / "packages" / "doctor" / "src" / "opagent_doctor" / "catalog.yaml"
OUT = ROOT / "apps" / "web" / "src" / "components" / "ProblemCard.generated.stories.tsx"


def build() -> str:
    codes = sorted(json.loads(ERRORS.read_text(encoding="utf-8")))
    cat = yaml.safe_load(CATALOG.read_text(encoding="utf-8")) or {}
    lines = [
        "// GENERATED by tools/gen_problem_stories.py — do not edit (VIS-003: one story per error code)",
        'import type { Meta, StoryObj } from "@storybook/react-vite";',
        'import { ProblemCard } from "./ProblemCard";',
        "",
        'const meta: Meta<typeof ProblemCard> = { title: "Errors/ProblemCard", component: ProblemCard };',
        "export default meta;",
        "type S = StoryObj<typeof ProblemCard>;",
        "",
    ]
    for code in codes:
        text = (
            json.loads(ERRORS.read_text(encoding="utf-8"))[code]["title"]
            + json.loads(ERRORS.read_text(encoding="utf-8"))[code]["message"]
        )
        params = {p: f"‹{p}›" for p in sorted(set(re.findall(r"\{(\w+)\}", text)))}
        fixes = []
        for f in (cat.get(code) or {}).get("fixes") or []:
            f = f["one_of"][0] if "one_of" in f else f
            fid = str(f.get("target") or f["type"]).split("(")[0].strip().replace(" ", "_").replace("-", "_")
            fixes.append({"id": fid, "type": f["type"], "target": f.get("target")})
        name = "".join(w.capitalize() for w in code.lower().split("_"))
        problem = json.dumps({"code": code, "params": params, "fixes": fixes}, ensure_ascii=False)
        lines.append(f"export const {name}: S = {{ args: {{ problem: {problem} }} }};")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("out of date:", OUT)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
