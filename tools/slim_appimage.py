"""Linux AppImage on the system WebKitGTK (08 §4.1, ADR-0022). CI only (desktop-build.yml).

linuxdeploy-plugin-gtk copies WebKitGTK, GTK, ICU and the rest of their closure (~180 MB uncompressed) into the
AppDir. 08 §4.1 has the AppImage depend on the system's WebKitGTK instead, as the .deb does through its package
dependencies. This tool:

1. extracts the AppImage built by Tauri;
2. removes every library in the closure of the build machine's ``libwebkit2gtk-4.1.so.0`` (all of it is
   guaranteed present wherever the system WebKitGTK is), the GTK hook and the GTK/GIO/pixbuf modules that pointed
   the app at bundled copies; ``usr/lib/<product>/`` (the app's resources: Python, pg pack) is never touched;
3. adds an AppRun hook that stops the launch with DESK_WEBVIEW_MISSING when the system WebKitGTK is absent;
4. repacks with the original AppImage runtime and the original squashfs compressor.

    python tools/slim_appimage.py <path/to/App.AppImage>      # in place
    python tools/slim_appimage.py --verify <path/to/App.AppImage>
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HOOK = "apprun-hooks/00-opagent-webview.sh"
WEBVIEW_SONAME = "libwebkit2gtk-4.1.so.0"
EXIT_WEBVIEW_MISSING = 78  # EX_CONFIG
GTK_HOOK = "apprun-hooks/linuxdeploy-plugin-gtk.sh"
MODULE_DIRS = ("webkit2gtk-4.1", "gdk-pixbuf-2.0", "gtk-3.0", "gio")
SHARE_DIRS = ("usr/share/glib-2.0/schemas",)
INSTALL = (
    "Debian/Ubuntu: sudo apt install libwebkit2gtk-4.1-0",
    "Fedora: sudo dnf install webkit2gtk4.1",
    "Arch: sudo pacman -S webkit2gtk-4.1",
)


def system_closure(soname: str = WEBVIEW_SONAME) -> set[str]:
    """The soname and everything it loads, as resolved on this (build) machine."""
    listing = subprocess.run(["ldconfig", "-p"], capture_output=True, text=True, check=True).stdout
    m = re.search(rf"^\s*{re.escape(soname)} .*=> (\S+)$", listing, re.M)
    if not m:
        raise SystemExit(f"{soname} is not installed on the build machine")
    ldd = subprocess.run(["ldd", m.group(1)], capture_output=True, text=True, check=True).stdout
    names = {soname}
    for line in ldd.splitlines():
        name = line.strip().split(" ", 1)[0]
        if ".so" in name and "/" not in name:
            names.add(name)
    return names


def _in_closure(name: str, closure: set[str]) -> bool:
    # exact soname, or the real file behind it (libfoo.so.0 → libfoo.so.0.2.7); never another major version
    return any(name == s or name.startswith(s + ".") for s in closure)


def _system_libs(appdir: Path) -> list[Path]:
    """Libraries linuxdeploy deployed (usr/lib, usr/lib/<triplet>), not the app's own resources tree."""
    lib = appdir / "usr" / "lib"
    if not lib.is_dir():
        return []
    out: list[Path] = []
    for d in [lib, *(p for p in lib.iterdir() if p.is_dir() and re.fullmatch(r"\w+-linux-gnu\w*", p.name))]:
        out += [p for p in d.iterdir() if (p.is_file() or p.is_symlink()) and ".so" in p.name]
    return out


def _hook_text() -> str:
    i18n = ROOT / "packages" / "i18n"
    zh = json.loads((i18n / "errors.zh-TW.json").read_text(encoding="utf-8"))["DESK_WEBVIEW_MISSING"]
    en = json.loads((i18n / "errors.en.json").read_text(encoding="utf-8"))["DESK_WEBVIEW_MISSING"]
    lines = [
        "DESK_WEBVIEW_MISSING",
        zh["message"].replace("{lib}", WEBVIEW_SONAME),
        en["message"].replace("{lib}", WEBVIEW_SONAME),
        f"{zh['cta']} / {en['cta']}:",
        *(f"  {c}" for c in INSTALL),
    ]
    msg = "\n".join(lines).replace("'", "'\\''")
    return f"""# Generated by tools/slim_appimage.py (ADR-0022, DESK-038). Sourced by AppRun before the app starts.
opa_webview_found() {{
  if [ -n "${{OPAGENT_WEBVIEW_LIBDIRS:-}}" ]; then opa_dirs="$OPAGENT_WEBVIEW_LIBDIRS"; else
    opa_dirs="/usr/lib/x86_64-linux-gnu /usr/lib64 /usr/lib /lib/x86_64-linux-gnu /lib64 /usr/local/lib"
    for opa_ld in ldconfig /sbin/ldconfig /usr/sbin/ldconfig; do
      if "$opa_ld" -p 2>/dev/null | grep -q '{WEBVIEW_SONAME} '; then return 0; fi
    done
  fi
  for opa_d in $opa_dirs; do
    if [ -e "$opa_d/{WEBVIEW_SONAME}" ]; then return 0; fi
  done
  return 1
}}
if ! opa_webview_found; then
  opa_msg='{msg}'
  printf '%s\\n' "$opa_msg" >&2
  if [ -n "${{DISPLAY:-}}${{WAYLAND_DISPLAY:-}}" ]; then
    if command -v zenity >/dev/null 2>&1; then zenity --error --no-markup --text="$opa_msg" 2>/dev/null
    elif command -v kdialog >/dev/null 2>&1; then kdialog --error "$opa_msg" 2>/dev/null
    elif command -v notify-send >/dev/null 2>&1; then notify-send "OpenPhotoAgent" "$opa_msg" 2>/dev/null
    fi
  fi
  exit {EXIT_WEBVIEW_MISSING}
fi
unset -f opa_webview_found
"""


def _rewrite_apprun(appdir: Path) -> None:
    """AppRun sources each hook by name: drop the GTK hook's line, source ours first, keep the rest."""
    apprun, wrapped = appdir / "AppRun", appdir / "AppRun.wrapped"
    hooks: list[str] = []
    if apprun.is_symlink() or not apprun.exists():  # no plugin hooks: AppRun is the app's entry point itself
        if apprun.is_symlink():
            target = os.readlink(apprun)
            apprun.unlink()
            wrapped.symlink_to(target)
    else:
        for m in re.finditer(r'apprun-hooks/"?([^"\s]+)"?', apprun.read_text(encoding="utf-8")):
            if m.group(1) != Path(GTK_HOOK).name and m.group(1) not in hooks:
                hooks.append(m.group(1))
    lines = ["#! /usr/bin/env bash", "# rewritten by tools/slim_appimage.py (ADR-0022)", ""]
    lines.append('this_dir="$(readlink -f "$(dirname "$0")")"')
    lines.append(f'source "$this_dir"/{HOOK}')
    lines += [f'source "$this_dir"/apprun-hooks/"{h}"' for h in hooks]
    lines += ["", 'exec "$this_dir"/AppRun.wrapped "$@"', ""]
    apprun.write_text("\n".join(lines), encoding="utf-8")
    apprun.chmod(0o755)


def slim(appdir: Path, closure: set[str]) -> list[str]:
    removed: list[str] = []

    def rm(p: Path) -> None:
        removed.append(p.relative_to(appdir).as_posix())
        if p.is_dir() and not p.is_symlink():
            shutil.rmtree(p)
        else:
            p.unlink()

    for p in _system_libs(appdir):
        if _in_closure(p.name, closure):
            rm(p)
    lib = appdir / "usr" / "lib"
    for d in [lib, *(p for p in lib.glob("*-linux-gnu*") if p.is_dir())] if lib.is_dir() else []:
        for name in MODULE_DIRS:
            if (d / name).exists():
                rm(d / name)
    for rel in (*SHARE_DIRS, GTK_HOOK):
        if (appdir / rel).exists():
            rm(appdir / rel)
    hook = appdir / HOOK
    hook.parent.mkdir(parents=True, exist_ok=True)
    hook.write_text(_hook_text(), encoding="utf-8")
    hook.chmod(0o755)
    _rewrite_apprun(appdir)
    return removed


def verify(appdir: Path, closure: set[str]) -> list[str]:
    """What of the WebKitGTK closure is still bundled (empty means DESK-037 holds)."""
    left = [p.relative_to(appdir).as_posix() for p in _system_libs(appdir) if _in_closure(p.name, closure)]
    if not (appdir / HOOK).is_file():
        left.append(f"missing {HOOK}")
    apprun = appdir / "AppRun"
    if not apprun.is_file() or apprun.is_symlink() or HOOK not in apprun.read_text(encoding="utf-8"):
        left.append(f"AppRun does not source {HOOK}")
    return sorted(left)


def _extract(appimage: Path, into: Path) -> Path:
    subprocess.run([str(appimage.resolve()), "--appimage-extract"], cwd=into, check=True, stdout=subprocess.DEVNULL)
    return into / "squashfs-root"


def _offset(appimage: Path) -> int:
    out = subprocess.run([str(appimage.resolve()), "--appimage-offset"], capture_output=True, text=True, check=True)
    return int(out.stdout.strip())


def _compressor(appimage: Path, offset: int) -> str:
    out = subprocess.run(
        ["unsquashfs", "-s", "-o", str(offset), str(appimage)], capture_output=True, text=True, check=True
    ).stdout
    m = re.search(r"Compression (\w+)", out)
    return m.group(1) if m else "gzip"


def main(argv: list[str]) -> int:
    check_only = "--verify" in argv
    appimage = Path(next(a for a in argv if not a.startswith("--")))
    os.environ.setdefault("APPIMAGE_EXTRACT_AND_RUN", "1")
    closure = system_closure()
    with tempfile.TemporaryDirectory() as tmp:
        ad = _extract(appimage, Path(tmp))
        if check_only:
            left = verify(ad, closure)
            for p in left:
                print(f"FAIL still bundled: {p}")
            print("OK   no WebKitGTK closure in the AppImage" if not left else "")
            return 1 if left else 0
        before = appimage.stat().st_size
        removed = slim(ad, closure)
        offset, comp = _offset(appimage), _compressor(appimage, _offset(appimage))
        sqfs = Path(tmp) / "new.squashfs"
        subprocess.run(
            ["mksquashfs", str(ad), str(sqfs), "-root-owned", "-noappend", "-comp", comp, "-quiet"], check=True
        )
        new = Path(tmp) / "new.AppImage"
        with appimage.open("rb") as src, new.open("wb") as dst:
            dst.write(src.read(offset))  # the original AppImage runtime
            with sqfs.open("rb") as fs:
                shutil.copyfileobj(fs, dst)
        new.chmod(0o755)
        shutil.move(str(new), str(appimage))
        print(
            f"removed {len(removed)} entries ({comp}): {before / 2**20:.1f} MiB -> {appimage.stat().st_size / 2**20:.1f} MiB"
        )
        for p in removed:
            print(f"  - {p}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
