"""Generate packages/core/src/opagent_core/data/lunar_new_year.csv (ADR-0008): Gregorian date of 正月初一 per
year, 1900–2099, from the ``lunardate`` package (dev-time only; the app reads the checked-in table).

    uv run --with lunardate python tools/gen_lunar_table.py [--check]
"""

from __future__ import annotations

import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "packages/core/src/opagent_core/data/lunar_new_year.csv"


def render() -> str:
    from lunardate import LunarDate

    rows = ["# year,lunar_new_year (正月初一, Gregorian) — generated by tools/gen_lunar_table.py"]
    for y in range(1900, 2100):
        d = LunarDate(y, 1, 1).toSolarDate()
        rows.append(f"{y},{d.isoformat()}")
    return "\n".join(rows) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        raise SystemExit(0 if OUT.read_text() == text else 1)
    OUT.write_text(text)
    print(f"wrote {OUT}")
